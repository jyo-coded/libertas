"""Legal drafts generated from an evidence pack (blueprint #33, #34, #35). Every document is a DRAFT for an officer
to review, complete and sign. Statutory wording must be checked against the official texts before use."""
from __future__ import annotations

import textwrap

DRAFT = "DRAFT: GENERATED BY LIBERTAS FOR OFFICER REVIEW. NOT VALID UNTIL REVIEWED, COMPLETED AND SIGNED."


def _wrap(text: str, width: int = 100) -> str:
    return "\n".join(textwrap.fill(p, width) if p.strip() else "" for p in text.split("\n"))


def _sim(ctx: dict) -> str:
    return ("\n*** SIMULATION: every organisation, person, wallet and exchange in this document is FICTIONAL "
            "(ShadowNet training data). ***\n" if ctx["simulation"] else "")


def _hash_table(ctx: dict) -> str:
    rows = [f"  {i + 1:>2}. {c['raw_file']}\n      captured {c['fetched_ist']}  (HTTP {c['status']}, {c['bytes']} bytes)\n"
            f"      SHA-256 {c['sha256']}\n      MD5     {c['md5']}" for i, c in enumerate(ctx["captures"])]
    return "\n".join(rows)


